import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true});
let hold=false,release;
try {
  const page=await browser.newPage();
  const url=process.env.ECHO_URL || 'http://127.0.0.1:3000';
  const boot=await (await page.request.get(url+'/api/bootstrap')).json();
  await page.addInitScript(config=>localStorage.setItem('echo-studio-session-v3',JSON.stringify({config,echo:[]})),{...boot.defaults,mode:'reroll'});
  const requests=[],responses=[],errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/solve',async route=>{
    requests.push(route.request().postDataJSON());
    if(hold){hold=false;await new Promise(resolve=>{release=resolve;});}
    await route.continue();
  });
  page.on('response', async r => { if (r.url().includes('/api/jobs/') && r.ok()) { const job = await r.json(); if (job.status === 'done') responses.push(job.result); } });
  const pause=()=>new Promise(r=>setTimeout(r,550));
  const ready=async()=>{await page.waitForFunction(()=>document.getElementById('result-status').textContent==='计算完成' && document.querySelector('.results-column').getAttribute('aria-busy')!=='true' && !document.getElementById('solve').disabled);await until(()=>responses.length===requests.length);};
  const until=async check=>{for(let i=0;i<200;i++){if(check())return;await new Promise(r=>setTimeout(r,25));}throw Error('Timed out');};
  const current=page.locator('[data-kind=echo][data-slot="0"][data-field=value]');
  const candidate=page.locator('[data-kind=candidate][data-slot="0"][data-field=value]');
  await page.goto(url);await page.locator('#solve:not([disabled])').waitFor();await pause();
  assert.equal(requests.length,0);
  assert.equal(await page.locator('#mode-description').innerText(),'使用频整器重抽声骸副词条。');
  await page.locator('#sample').click();await current.selectOption('105');await pause();
  assert.equal(requests.length,0,'Starting Echo edits require explicit solving');
  await page.locator('#candidate-details').evaluate(el => { el.open = true; });
  assert.equal(await page.locator('#use-candidate').count(),0);
  await page.locator('#copy-candidate').click();await pause();
  assert.equal(requests.length,0,'Candidates cannot implicitly confirm a starting Echo');
  await page.locator('#clear-candidate').click();
  await page.locator('#solve').click();await ready();
  assert.equal(requests.length,1);
  const original=structuredClone(requests.at(-1).echo);
  const expected=await page.locator('#resources').innerText();
  await page.locator('#copy-candidate').click();await ready();
  assert.equal(responses.at(-1).comparison.accept,true);
  await candidate.selectOption('63');await ready();
  assert.equal(responses.at(-1).comparison.accept,false);
  assert.equal(responses.at(-1).cached,true);
  assert.deepEqual(requests.at(-1).echo,original);
  assert.equal(await current.inputValue(),'105');
  assert.equal(await page.locator('#resources').innerText(),expected,'Candidate comparison does not change the baseline');
  let before=requests.length;
  await page.locator('[data-kind=candidate][data-slot="4"][data-field=type]').selectOption('');await pause();
  assert.equal(requests.length,before,'Partial candidates must not submit');
  assert.equal(await page.locator('#comparison-panel').isVisible(),true);
  assert.equal(await page.locator('#accept-candidate').isVisible(),false);
  await page.locator('[data-kind=candidate][data-slot="4"][data-field=type]').selectOption('9');await ready();
  assert.equal(requests.length,before+1);
  // Editing the current Echo queries the cached policy automatically.
  before=requests.length;
  await current.selectOption('93');await ready();
  assert.equal(requests.length,before+1);
  assert.equal(requests.at(-1).echo[0][1],93);
  assert.equal(responses.at(-1).cached,true);
  await candidate.selectOption('105');await ready();
  hold=true;release=null;
  await candidate.selectOption('75');await until(()=>Boolean(release));
  assert.equal(await page.locator('#accept-candidate').isDisabled(),true,'Do not accept a stale comparison');
  await candidate.selectOption('81');await candidate.selectOption('105');before=requests.length;
  release();await ready();
  assert.equal(requests.length,before+1);
  assert.equal(requests.at(-1).candidate[0][1],105);
  // Queued Echo edits also query the latest baseline automatically.
  hold=true;release=null;
  await candidate.selectOption('75');await until(()=>Boolean(release));
  await candidate.selectOption('99');await current.selectOption('87');before=requests.length;
  release();await ready();
  assert.equal(requests.length,before+1);
  assert.equal(requests.at(-1).echo[0][1],87);
  assert.equal(responses.at(-1).cached,true);
  before=requests.length;
  await page.locator('#target').fill('65');await candidate.selectOption('105');await pause();
  assert.equal(requests.length,before);
  await page.locator('[data-language=en]').click();
  assert.equal(await page.locator('#mode-description').innerText(),'Use Transducers to reroll Echo Substats.');
  assert.equal(await page.locator('#compute-hint').innerText(),'Confirm scoring and target, then solve the policy');
  await page.locator('[data-language="zh-CN"]').click();
  await page.locator('#solve').click();await ready();
  const accepted=structuredClone(requests.at(-1).candidate);
  const nextCost=responses.at(-1).comparison.candidate_cost;
  before=requests.length;
  await page.locator('#accept-candidate').click();await ready();
  assert.equal(requests.length,before+1,'Accepting immediately queries the next action');
  assert.deepEqual(requests.at(-1).echo,accepted);
  assert.equal(requests.at(-1).candidate,null);
  assert.equal(responses.at(-1).cached,true);
  assert.equal(responses.at(-1).frequencies,nextCost);
  assert.equal(await current.inputValue(),'105');
  assert.equal(await page.locator('#comparison-panel').isVisible(),true);
  assert.equal(await page.locator('#accept-candidate').isVisible(),false);
  assert.equal(await page.locator('[data-kind=candidate][data-slot="0"][data-field=type]').inputValue(),'');
  assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('echo-studio-session-v3')).echo),accepted);
  before=requests.length;
  await current.selectOption('93');await ready();
  assert.equal(requests.length,before+1,'Current Echo edits update even without a candidate');
  assert.equal(requests.at(-1).candidate,null);
  assert.equal(responses.at(-1).cached,true);
  before=requests.length;
  await page.locator('[data-kind=echo][data-slot="4"][data-field=type]').selectOption('');await pause();
  assert.equal(requests.length,before,'Incomplete current Echo waits for five Substats');
  await page.locator('[data-kind=echo][data-slot="4"][data-field=type]').selectOption('9');await ready();
  assert.equal(requests.length,before+1);
  // Continue the same session, including editing a partial candidate during acceptance.
  await page.locator('#copy-candidate').click();await ready();
  await candidate.selectOption('99');await ready();
  hold=true;release=null;
  await page.locator('#accept-candidate').click();await until(()=>Boolean(release));
  await page.locator('#copy-candidate').click();
  await page.locator('[data-kind=candidate][data-slot="4"][data-field=type]').selectOption('');
  before=requests.length;release();await ready();
  assert.equal(requests.length,before+1);
  assert.equal(requests.at(-1).echo[0][1],99);
  assert.equal(requests.at(-1).candidate,null);
  assert.equal(responses.at(-1).cached,true);
  // A candidate that meets the target ends with a keep recommendation.
  await page.locator('#target').fill('0');
  await page.locator('#clear-candidate').click();
  await page.locator('#solve').click();await ready();
  await page.locator('#copy-candidate').click();await ready();
  await page.locator('[data-language=en]').click();
  assert.equal(await page.locator('#accept-candidate').innerText(),'Accept candidate');
  await page.locator('[data-language="zh-CN"]').click();
  await page.locator('#accept-candidate').click();await ready();
  assert.equal(responses.at(-1).decision,'keep');
  assert.equal(responses.at(-1).frequencies,0);
  assert.deepEqual(errors,[]);
  console.log('Reroll workflow passed: manual confirmation, automatic comparison, candidate acceptance and continuation, cached policy reuse, partial inputs, queued edits, stale-action protection, target completion and bilingual guidance.');
} finally {if(release)release();await browser.close();}
